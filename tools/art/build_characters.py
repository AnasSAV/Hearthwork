"""
Build the character atlases from LimeZu's Modern Interiors character generator (16x16 set).

    python tools/art/build_characters.py "D:/Personal/FocusTown-art"

Only the rows the game uses are kept (idle, walk, sit), cropped to 24 frames each, and every
part is packed into one atlas per category under client/public/assets/characters/. A manifest
of part ids and atlas cells is written to shared/src/avatarParts.ts.

LimeZu sheets: 16x32 frames, 56 per row. Row 1 = idle and row 2 = walk (6 frames per
direction, ordered right, up, left, down); row 4 = sitting (6 right, then 6 left).
The source art is licensed (credit LimeZu, no redistribution of the pack itself), so only
these derived atlases are committed. Needs Python 3 + Pillow; only for regenerating art.
"""
import os
import re
import sys

from PIL import Image

SRC = sys.argv[1] if len(sys.argv) > 1 else "D:/Personal/FocusTown-art"
GEN = os.path.join(SRC, "Interior", "2_Characters", "Character_Generator")
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "client", "public", "assets", "characters")
MANIFEST = os.path.join(ROOT, "shared", "src", "avatarParts.ts")

FW, FH = 16, 32
FRAMES = 24  # 6 frames x 4 directions
ROWS = [(1, FRAMES), (2, FRAMES), (4, 12)]  # (source row, frames): idle, walk, sit
CELL_W, CELL_H = FW * FRAMES, FH * len(ROWS)  # 384 x 96
COLS = 5  # cells per atlas row -> 1920 px wide

CATEGORIES = [
    # (category, folder, file prefix)
    ("body", "Bodies", "Body_"),
    ("eyes", "Eyes", "Eyes_"),
    ("outfit", "Outfits", "Outfit_"),
    ("hair", "Hairstyles", "Hairstyle_"),
    ("acc", "Accessories", "Accessory_"),
]


def natural(s):
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", s)]


# LimeZu's outline and shadow greys, shared by every part.
OUTLINE = {(58, 58, 80), (70, 70, 94)}


def swatch(cell):
    """Most common non-outline colour of the front idle frame, for the creator's colour dots."""
    frame = cell.crop((18 * FW, 0, 19 * FW, FH))
    counts = {}
    data = frame.tobytes()
    for r, g, b, a in (data[i : i + 4] for i in range(0, len(data), 4)):
        if a > 200 and (r, g, b) not in OUTLINE and r * 0.3 + g * 0.59 + b * 0.11 > 30:
            counts[(r, g, b)] = counts.get((r, g, b), 0) + 1
    r, g, b = max(counts, key=counts.get) if counts else (0, 0, 0)
    return f"#{r:02x}{g:02x}{b:02x}"


def crop_part(path):
    sheet = Image.open(path).convert("RGBA")
    cell = Image.new("RGBA", (CELL_W, CELL_H), (0, 0, 0, 0))
    for i, (row, frames) in enumerate(ROWS):
        # The sit row only has 12 frames; some sheets print a guide label after them.
        strip = sheet.crop((0, row * FH, frames * FW, row * FH + FH))
        cell.paste(strip, (0, i * FH))
    return cell


os.makedirs(OUT, exist_ok=True)
manifest = {}
for category, folder, prefix in CATEGORIES:
    files = sorted(
        (f for f in os.listdir(os.path.join(GEN, folder, "16x16")) if f.startswith(prefix) and f.endswith(".png")),
        key=natural,
    )
    rows = (len(files) + COLS - 1) // COLS
    atlas = Image.new("RGBA", (CELL_W * COLS, CELL_H * rows), (0, 0, 0, 0))
    ids, colors = [], []
    for i, f in enumerate(files):
        cell = crop_part(os.path.join(GEN, folder, "16x16", f))
        atlas.paste(cell, ((i % COLS) * CELL_W, (i // COLS) * CELL_H))
        ids.append(f[:-4])
        colors.append(swatch(cell))
    if atlas.height > 4096:
        raise SystemExit(f"{category} atlas is {atlas.height}px tall; increase COLS")
    atlas.save(os.path.join(OUT, f"{category}.png"), optimize=True)
    manifest[category] = (ids, colors)
    print(f"{category}: {len(ids)} parts -> {atlas.size}")

lines = [
    "// GENERATED by tools/art/build_characters.py from LimeZu's Modern Interiors character",
    "// generator. Part ids are the source file names; the index is the cell in that category's",
    "// atlas (client/public/assets/characters/<category>.png, 5 cells per row, 384x96 each).",
    "",
    "export const AVATAR_ATLAS = { cellWidth: 384, cellHeight: 96, columns: 5 } as const;",
    "",
    "export const AVATAR_PART_IDS = {",
]
for category, (ids, colors) in manifest.items():
    lines.append(f"  {category}: [")
    for chunk in range(0, len(ids), 4):
        lines.append("    " + " ".join(f"'{i}'," for i in ids[chunk : chunk + 4]))
    lines.append("  ],")
lines += ["} as const;", "", "/** Main colour of each part (same order), for colour swatches. */", "export const AVATAR_PART_COLORS: Record<keyof typeof AVATAR_PART_IDS, readonly string[]> = {"]
for category, (ids, colors) in manifest.items():
    lines.append(f"  {category}: [")
    for chunk in range(0, len(colors), 8):
        lines.append("    " + " ".join(f"'{c}'," for c in colors[chunk : chunk + 8]))
    lines.append("  ],")
lines += ["};", ""]
with open(MANIFEST, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines))
print("wrote", MANIFEST)
