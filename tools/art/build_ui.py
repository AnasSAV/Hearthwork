"""
Build UI sprites from LimeZu's Modern Interiors `4_User_Interface_Elements` (16x16 sheet).

    python tools/art/build_ui.py "D:/Personal/FocusTown-art"

Writes client/public/assets/ui/ui.png + ui.json (Phaser atlas, JSON hash) and
client/src/ui/uiSprites.ts (generated frame rectangles for CSS). Frames:
  emote:<name>   speech-bubble emotes players can pop over their heads
  timer:<i>      8-frame bubble shown over players who are focusing
  typing:<i>     8-frame "…" bubble
The bubbles sit half a tile off the 16px grid, so each frame is 16x18 cut at measured rows.
"""
import json
import os
import sys

from PIL import Image

SRC = sys.argv[1] if len(sys.argv) > 1 else "D:/Personal/FocusTown-art"
SHEET = os.path.join(SRC, "Interior", "4_User_Interface_Elements", "UI_16x16.png")
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "client", "public", "assets", "ui")
MANIFEST = os.path.join(ROOT, "client", "src", "ui", "uiSprites.ts")

FW, FH = 16, 18
# Top edge (px) of each bubble row in the sheet.
ROW_Y = {1: 8, 3: 40, 9: 136, 13: 200}

# Emote name -> (sheet row, column). Order is the order players see them in the picker.
EMOTES = {
    "heart": (1, 6),
    "music": (1, 12),
    "zzz": (1, 11),
    "idea": (1, 9),
    "question": (1, 8),
    "sun": (3, 14),
    "moon": (1, 14),
    "sweat": (3, 15),
    "star": (3, 5),
    "trophy": (1, 16),
}

sheet = Image.open(SHEET).convert("RGBA")
frames = {}


def cut(row, col):
    y = ROW_Y[row]
    return sheet.crop((col * 16, y, col * 16 + FW, y + FH))


pieces = [(f"emote:{name}", cut(r, c)) for name, (r, c) in EMOTES.items()]
pieces += [(f"timer:{i}", cut(9, i)) for i in range(8)]
pieces += [(f"typing:{i}", cut(13, i)) for i in range(8)]

COLS = 10
atlas = Image.new("RGBA", (COLS * FW, -(-len(pieces) // COLS) * FH))
for i, (name, im) in enumerate(pieces):
    x, y = (i % COLS) * FW, (i // COLS) * FH
    atlas.paste(im, (x, y))
    frames[name] = {"frame": {"x": x, "y": y, "w": FW, "h": FH}, "rotated": False,
                    "trimmed": False, "spriteSourceSize": {"x": 0, "y": 0, "w": FW, "h": FH},
                    "sourceSize": {"w": FW, "h": FH}}

os.makedirs(OUT, exist_ok=True)
atlas.save(os.path.join(OUT, "ui.png"), optimize=True)
with open(os.path.join(OUT, "ui.json"), "w", encoding="utf-8", newline="\n") as fh:
    json.dump({"frames": frames, "meta": {"image": "ui.png",
               "size": {"w": atlas.width, "h": atlas.height}, "scale": "1"}}, fh, indent=1)

lines = [
    "// GENERATED by tools/art/build_ui.py from LimeZu's Modern Interiors UI elements.",
    "",
    f"export const UI_SHEET = {{ url: '/assets/ui/ui.png', width: {atlas.width}, height: {atlas.height} }} as const;",
    "",
    "/** Frame name -> [x, y, w, h] in pixels. */",
    "export const UI_FRAMES: Record<string, readonly [number, number, number, number]> = {",
]
for name, f in frames.items():
    r = f["frame"]
    lines.append(f"  '{name}': [{r['x']}, {r['y']}, {r['w']}, {r['h']}],")
lines += ["};", ""]
with open(MANIFEST, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines))
print(f"ui: {len(frames)} frames {atlas.size}")
