/**
 * Writes supabase/seed.sql from the shared catalog (shared/src/catalog.ts).
 * Run: npm run seed:items. The seed upserts, so it is safe to re-run on a live database.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CATALOG, spriteKey } from '../../shared/src/catalog.js';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function seedSql(): string {
  const rows = CATALOG.map(
    (i) =>
      `  (${[
        q(i.id),
        q(i.name),
        q(i.category),
        i.price,
        i.sprite.w,
        i.sprite.h,
        q(i.layer),
        q(spriteKey(i.sprite)),
        i.minHouseLevel,
        i.surfaceHost ? 'true' : 'false',
      ].join(', ')})`,
  );
  return [
    '-- GENERATED by tools/db/generate-seed.ts from shared/src/catalog.ts. Do not edit by hand.',
    '-- Loaded by `supabase db reset` locally; paste into the SQL editor for hosted projects.',
    '-- (The house_levels ladder lives in the core migration because the signup trigger needs it.)',
    '',
    'insert into public.items',
    '  (id, name, category, price, footprint_w, footprint_h, layer, sprite_key, min_house_level, surface_host)',
    'values',
    rows.join(',\n'),
    'on conflict (id) do update set',
    '  name = excluded.name, category = excluded.category, price = excluded.price,',
    '  footprint_w = excluded.footprint_w, footprint_h = excluded.footprint_h, layer = excluded.layer,',
    '  sprite_key = excluded.sprite_key, min_house_level = excluded.min_house_level,',
    '  surface_host = excluded.surface_host, active = true;',
    '',
    '-- Items removed from the catalog stay (inventories reference them) but leave the shop.',
    `update public.items set active = false where id not in (${CATALOG.map((i) => q(i.id)).join(', ')});`,
    '',
  ].join('\n');
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const out = fileURLToPath(new URL('../../supabase/seed.sql', import.meta.url));
  writeFileSync(out, seedSql());
  console.log(`Wrote ${CATALOG.length} items to supabase/seed.sql`);
}
