export type IconName = keyof typeof MASKS;

/** One SVG path of horizontal runs per mask row; cached per icon. */
const paths = new Map<IconName, string>();
function pathFor(name: IconName): string {
  let d = paths.get(name);
  if (d !== undefined) return d;
  d = '';
  MASKS[name].forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      const start = x;
      while (row[x] === '#') x++;
      d += `M${start} ${y}h${x - start}v1h-${x - start}z`;
    }
  });
  paths.set(name, d);
  return d;
}

export function Icon({ name, size = 18 }: { name: IconName; size?: number }) {
  return (
    <svg
      className="icon"
      width={size}
      height={size}
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      aria-hidden="true"
    >
      <path d={pathFor(name)} fill="currentColor" />
    </svg>
  );
}
